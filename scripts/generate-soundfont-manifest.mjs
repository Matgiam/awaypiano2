/**
 * Soundfont manifest generator.
 *
 * Scans `public/assets/soundfonts` and emits a fully-typed TypeScript module at
 * `src/lib/soundfont-manifest.ts`. Doing this at build time (rather than reading
 * the directory at runtime) keeps the manifest available to Client Components,
 * which have no filesystem access.
 *
 * Run with: `npm run soundfonts:manifest`
 */

import { mkdir, readdir, stat, writeFile } from "node:fs/promises";
import { join, relative, extname, basename, dirname, sep } from "node:path";
import { fileURLToPath } from "node:url";

const PROJECT_ROOT = fileURLToPath(new URL("..", import.meta.url));
const SOUNDFONT_DIR = join(PROJECT_ROOT, "public", "assets", "soundfonts");
const OUTPUT_FILE = join(PROJECT_ROOT, "src", "lib", "soundfont-manifest.ts");

/** Extensions we treat as loadable SoundFont banks. */
const SOUNDFONT_EXTENSIONS = new Set([".sf2", ".sf3"]);

/**
 * Human-friendly labels for the directory names inherited from the asset
 * library. The source folders are inconsistently cased ("Guitars" vs "bass"),
 * so we normalise them here rather than trusting the filesystem.
 */
const FAMILY_LABELS = {
  keyboards: "Keyboards",
  bass: "Bass",
  guitars: "Guitars & Plucked",
  strings: "Strings",
  winds: "Winds & Brass",
  choirs: "Choirs",
  percussion: "Percussion & Mallets",
  "synth pads": "Synth & Pads",
  misc: "Miscellaneous",
  "": "Uncategorised",
};

/** Recursively collect every soundfont file beneath `dir`. */
async function collectSoundfonts(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const fullPath = join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await collectSoundfonts(fullPath)));
    } else if (SOUNDFONT_EXTENSIONS.has(extname(entry.name).toLowerCase())) {
      files.push(fullPath);
    }
  }

  return files;
}

/** Turn "E.Piano Rhodes" into "e-piano-rhodes" for use in stable ids. */
function slugify(value) {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

/**
 * Build a browser-safe URL. Filenames contain spaces and dots ("Slap Bass 2.sf2",
 * "E.Piano FM.sf3"), so every path segment is encoded individually — encoding the
 * whole path at once would escape the forward slashes too.
 */
function toPublicUrl(relativePath) {
  const segments = relativePath.split(sep).map(encodeURIComponent);
  return `/assets/soundfonts/${segments.join("/")}`;
}

async function main() {
  const files = (await collectSoundfonts(SOUNDFONT_DIR)).sort((a, b) =>
    a.localeCompare(b),
  );

  const entries = await Promise.all(
    files.map(async (file) => {
      const relativePath = relative(SOUNDFONT_DIR, file);
      const segments = relativePath.split(sep);
      // Files sitting directly in the root have no family folder.
      const familyDir = segments.length > 1 ? segments[0] : "";
      const extension = extname(file).toLowerCase();
      const name = basename(file, extension);
      const { size } = await stat(file);

      return {
        id: `${slugify(familyDir) || "root"}/${slugify(name)}`,
        name,
        family: slugify(familyDir) || "root",
        familyLabel:
          FAMILY_LABELS[familyDir.toLowerCase()] ?? FAMILY_LABELS[""],
        url: toPublicUrl(relativePath),
        format: extension.slice(1),
        bytes: size,
      };
    }),
  );

  // Guard against two banks colliding on the same id (e.g. a .sf2 and .sf3 of
  // the same name), which would break React keys and lookup maps downstream.
  const seen = new Set();
  for (const entry of entries) {
    if (seen.has(entry.id)) {
      throw new Error(
        `Duplicate soundfont id "${entry.id}". Rename one of the source files.`,
      );
    }
    seen.add(entry.id);
  }

  const totalBytes = entries.reduce((sum, entry) => sum + entry.bytes, 0);

  const contents = `// AUTO-GENERATED by scripts/generate-soundfont-manifest.mjs — do not edit by hand.
// Regenerate with: npm run soundfonts:manifest

/** A single SoundFont bank available in \`public/assets/soundfonts\`. */
export interface SoundfontEntry {
  /** Stable identifier, e.g. \`"keyboards/concert-grand"\`. */
  id: string;
  /** Display name taken from the filename. */
  name: string;
  /** Slugified family folder, e.g. \`"synth-pads"\`. */
  family: string;
  /** Human-readable family label for UI grouping. */
  familyLabel: string;
  /** Public URL, percent-encoded and safe to pass to \`fetch\`. */
  url: string;
  /** Container format. SF3 stores Vorbis-compressed samples. */
  format: "sf2" | "sf3";
  /** File size in bytes, used to show download progress. */
  bytes: number;
}

export const SOUNDFONTS: readonly SoundfontEntry[] = ${JSON.stringify(entries, null, 2)} as const;

/** Total size of the bundled soundfont library, in bytes. */
export const SOUNDFONT_LIBRARY_BYTES = ${totalBytes};

/** The bank loaded on first paint — a full concert grand piano. */
export const DEFAULT_SOUNDFONT_ID = "keyboards/concert-grand";

/** Fast id -> entry lookup for the audio engine. */
export const SOUNDFONT_BY_ID: ReadonlyMap<string, SoundfontEntry> = new Map(
  SOUNDFONTS.map((entry) => [entry.id, entry]),
);

/** Families in display order, each with its member banks. */
export function groupSoundfontsByFamily(): {
  family: string;
  label: string;
  entries: SoundfontEntry[];
}[] {
  const groups = new Map<string, { family: string; label: string; entries: SoundfontEntry[] }>();

  for (const entry of SOUNDFONTS) {
    let group = groups.get(entry.family);
    if (!group) {
      group = { family: entry.family, label: entry.familyLabel, entries: [] };
      groups.set(entry.family, group);
    }
    group.entries.push(entry);
  }

  return [...groups.values()];
}
`;

  await mkdir(dirname(OUTPUT_FILE), { recursive: true });
  await writeFile(OUTPUT_FILE, contents, "utf8");

  console.log(
    `Wrote ${entries.length} soundfonts (${(totalBytes / 1024 / 1024).toFixed(1)} MB) to src/lib/soundfont-manifest.ts`,
  );
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
